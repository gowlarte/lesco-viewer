/** @returns {string} SVG inline com traço de 1.5px, herdando currentColor. */
export function icone(nome, tamanho = 16, traco = 1.5) {
  return `<svg width="${tamanho}" height="${tamanho}" viewBox="0 0 24 24" fill="none"
    stroke="currentColor" stroke-width="${traco}" stroke-linecap="round"
    stroke-linejoin="round" aria-hidden="true" focusable="false">${P[nome] || ''}</svg>`;
}

export const temIcone = (nome) => nome in P;

/**
 * Troca `data-icone="nome"` pelo SVG correspondente, no início do elemento.
 * Deixa o HTML das páginas legível — o markup declara o ícone, não 400 bytes de path.
 */
export function hidratarIcones(raiz = document) {
  for (const el of raiz.querySelectorAll('[data-icone]')) {
    const nome = el.dataset.icone;
    delete el.dataset.icone;
    if (temIcone(nome)) el.insertAdjacentHTML('afterbegin', icone(nome, Number(el.dataset.icTam) || 16));
  }
}
